class SupportProvider {
  final String id;
  final String name;
  final String type;
  final String organization;
  final String phone;
  final String email;
  final String division;
  final bool isProBono;

  SupportProvider({
    required this.id,
    required this.name,
    required this.type,
    required this.organization,
    required this.phone,
    required this.email,
    required this.division,
    required this.isProBono,
  });
}
