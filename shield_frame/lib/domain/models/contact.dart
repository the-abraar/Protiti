class TrustedContact {
  final String id;
  final String name;
  final String phone;
  final String email;
  final String relationship;
  final bool isEmergency;

  TrustedContact({
    required this.id,
    required this.name,
    required this.phone,
    required this.email,
    required this.relationship,
    required this.isEmergency,
  });
}
